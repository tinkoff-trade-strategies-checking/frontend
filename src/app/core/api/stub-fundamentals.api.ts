@Injectable({ providedIn: 'root' })
export class StubFundamentalsApi implements FundamentalsApi {
  private readonly registry = injectSessionRegistry();

  async getPaperFundamentals(ticker: string): Promise<PaperFundamentals | null> {
    const normalized = ticker.trim().toUpperCase();
    return STUB_FUNDAMENTALS[normalized] ?? null;
  }

  async getSessionFundamentals(sessionId: string): Promise<SessionFundamentalsResponse> {
    const record = this.registry?.get(sessionId);

    // INV-7: активная слепая сессия НИКОГДА не раскрывает фундаментальные показатели.
    if (record && record.blind && !record.finished) {
      return { hiddenByBlindMode: true, asOfDate: null, items: [] };
    }

    // По умолчанию (неизвестный id из дефолтной слепой сессии S-0104) соблюдаем INV-7.
    if (!record && sessionId === 'S-0104') {
      return { hiddenByBlindMode: true, asOfDate: null, items: [] };
    }

    const tickers: readonly string[] = record?.paperIds?.length
      ? record.paperIds
      : ['SBER', 'GAZP', 'YDEX', 'GMKN', 'MGNT'];

    const items: SessionPaperFundamentalsItem[] = tickers.map((rawTicker) => {
      const ticker = rawTicker.toUpperCase();
      const snapshot = STUB_FUNDAMENTALS[ticker] ?? null;
      const meta = PAPER_META[ticker] ?? { name: ticker, sector: 'Прочее' };
      return {
        paperId: ticker,
        ticker,
        name: meta.name,
        sector: meta.sector,
        available: snapshot !== null,
        snapshot,
      };
    });

    return {
      hiddenByBlindMode: false,
      asOfDate: '2026-03-31',
      items,
    };
  }
}
